"""Render the candidate taxonomy from its JSON definition, using only the standard library.

Included in build_readme.py and its --check mode. Does not change catalog labels.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFINITION = "docs/taxonomy-proposal-v0.1.json"
PAGE = "docs/taxonomy-proposal.md"
REPORT = "taxonomy-research-2026-10-16.md"
REVIEW_NOTES = {
    "D08": "财产、商业行为、知识产权及人格权益的聚合依据需要复审。",
    "D09": "无意事实错误与信息传播操纵的同域组织方式需要比较。",
    "D11": "控制属性与失效环节的层级关系需要整理。",
    "D12": "社会、文化与环境影响的范围偏宽，需要比较拆分方案。",
}


def source_links(ids):
    return " · ".join(f"[{sid}]({REPORT}#{sid.lower()})" for sid in ids)


def validate_definition(proposal):
    """Check internal references and required definitions, without fixing category counts."""
    sources = [source["id"] for source in proposal["sources"]]
    domains = proposal["risk_domains"]
    children = [child for domain in domains for child in domain["children"]]
    labels = domains + children
    ids = [label["id"] for label in labels]
    if len(sources) != len(set(sources)) or len(ids) != len(set(ids)):
        raise ValueError("Duplicate taxonomy source or risk ID")
    for label in labels:
        if not label.get("definition") or not label.get("source_ids"):
            raise ValueError("Missing definition or sources: " + label["id"])
        if not set(label["source_ids"]) <= set(sources):
            raise ValueError("Unknown source: " + label["id"])
    for domain in domains:
        for child in domain["children"]:
            if not child["id"].startswith(domain["id"] + ".") or not child.get("boundary"):
                raise ValueError("Missing boundary or invalid parent: " + child["id"])
    for rule in proposal["legacy_migration"]:
        if not set(rule.get("risk_candidates", [])) <= set(ids):
            raise ValueError("Unknown legacy migration target: " + rule["old_id"])


def render(proposal):
    validate_definition(proposal)
    domains = proposal["risk_domains"]
    child_count = sum(len(domain["children"]) for domain in domains)
    lines = [
        "<!-- Generated by scripts/build_taxonomy.py; edit the JSON definition, then run scripts/build_readme.py. -->",
        "# Candidate Taxonomy | 候选风险分类",
        "",
        "[← 资源目录](../README.md) · [总览](taxonomy.md) · [设计依据](taxonomy-rationale.md) · **候选分类** · [验证计划](taxonomy-validation.md) · [研究附录](taxonomy-research-2026-10-16.md)",
        "",
        f'> **{proposal["version"]} · 待验证提案 · {proposal["as_of"]}**',
        ">",
        f"> 当前包含 **{len(domains)} 个一级领域、{child_count} 个二级类型**。用于描述评测资源的风险覆盖目标，类别数与边界仍可调整。尚未用于全量目录重标。",
        "",
        "Candidate risk coverage labels for evaluation resources. Definitions and source mappings remain subject to validation.",
        "",
        "[为什么这样分？](taxonomy-rationale.md) · [验证计划](taxonomy-validation.md) · [机器可读 JSON](taxonomy-proposal-v0.1.json) · [旧 19 类候选迁移](taxonomy-research-2026-10-16.md#migration)",
        "",
        "## 领域一览",
        "",
        "点击领域名进入定义，再展开二级类型。多标签允许重叠；来源编号表示本项目综合参考关系，具体构念与条款对应需结合研究附录核对。",
        "",
        "| ID | 候选领域 | 二级数 | 边界状态 |",
        "| --- | --- | ---: | --- |",
    ]
    for domain in domains:
        did = domain["id"]
        status = "优先复审" if did in REVIEW_NOTES else "待试标"
        lines.append(f'| `{did}` | [{domain["name_zh"]}](#{did.lower()}) | {len(domain["children"])} | {status} |')
    lines += [
        "",
        "## 阅读约定",
        "",
        "- **按实际任务取证。** 套件声明覆盖某领域，不代表其全部样本具有该标签。",
        "- **区分其他维度。** 越狱／注入归机制，Agent／MCP 归系统背景，过拒归测量目标，规范条款保留法域与版本。",
        "- **保留未知。** 未取得证据、未测、不适用、待审分别记录。",
        "- **匹配证据层级。** 资源覆盖标签、样本内容、知识能力、真实行动与社会影响各有证据要求。",
        "",
    ]
    for domain in domains:
        did = domain["id"]
        lines += [
            f'<a id="{did.lower()}"></a>',
            "",
            f'## {did} · {domain["name_zh"]}',
            "",
            domain["definition"],
            "",
            "**综合参考：** " + source_links(domain["source_ids"]),
            "",
        ]
        if did in REVIEW_NOTES:
            lines += ["> **复审重点：** " + REVIEW_NOTES[did] + " [查看设计讨论](taxonomy-rationale.md)。", ""]
        lines += [
            "<details>",
            f'<summary><strong>展开 {len(domain["children"])} 个二级定义、边界与来源</strong></summary>',
            "",
            "**一级纳入范围：** " + "；".join(domain["include"]),
            "",
            "**一级排除／转介：** " + "；".join(domain["exclude"]),
            "",
        ]
        for child in domain["children"]:
            lines += [
                f'### {child["id"]} · {child["name_zh"]}',
                "",
                "**定义：** " + child["definition"],
                "",
                "**边界：** " + child["boundary"],
                "",
                "**综合参考：** " + source_links(child["source_ids"]),
                "",
            ]
        lines += ["</details>", "", "[↑ 返回领域一览](#领域一览)", ""]
    lines += [
        "---",
        "",
        "**定义来源：** 本页由 [候选 JSON](taxonomy-proposal-v0.1.json) 自动生成。实质修改应同步写入[变更记录](taxonomy-validation.md)，并提交来源定位和边界案例。",
        "",
    ]
    return "\n".join(lines)


def outputs():
    proposal = json.loads((ROOT / DEFINITION).read_text(encoding="utf-8"))
    return {PAGE: render(proposal).encode("utf-8")}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for relative, content in outputs().items():
        target = ROOT / relative
        if args.check:
            if not target.exists() or target.read_bytes() != content:
                raise SystemExit("Generated taxonomy page is out of date: " + relative)
        else:
            target.write_bytes(content)
    print("Taxonomy page is current." if args.check else "Generated candidate taxonomy page.")
